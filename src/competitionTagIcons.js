export function getDisplayTagLabel(value) {
  return String(value || "")
    .trim()
    .replace(/^#+\s*/, "")
    .replace(/\s+/g, " ");
}

export function getCompetitionTagIcon(value) {
  const tag = getDisplayTagLabel(value).toLocaleLowerCase("id-ID");
  return tagIconMatchers.find(([pattern]) => pattern.test(tag))?.[1] || Tag;
}
